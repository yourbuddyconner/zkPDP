//! cedar-to-noir: compile a validated Cedar policy set to a Noir circuit,
//! through the Term IR of Cedar's symbolic compiler.
//!
//!   cedar-to-noir compile  <repo> <set> <out dir>   write a Noir project and one input file per corpus request
//!   cedar-to-noir coverage <repo>                   one JSON line per corpus set: what compiles and what blocks it

mod gen;

use cedar_policy::{Effect, PolicySet, Schema};
use cedar_policy_symcc::op::Op;
use cedar_policy_symcc::term::Term;
use cedar_policy_symcc::{never_matches_asserts, CompiledPolicy, SymEnv};
use envelope::{
    block_bytes, canonical_request, hex_hash, parse_hex_hash, record_block, set_block, sha256, uid_text, Kind, Layouts,
    RecordStore, MAX_ANC, MAX_ATTRS, MAX_SET,
};
use gen::{EnvGen, Needs};
use serde_json::{json, Value};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::str::FromStr;

const MAX_DEPTH: usize = 12;
const PRELUDE: &str = include_str!("prelude.nr");

/// Environments whose functions are identical share one function.
struct Group {
    body: String,
    needs: Needs,
    envs: Vec<(String, String, String)>, // principal type, action name, resource type
}

struct Compiled {
    groups: Vec<Group>,
    layouts: Layouts,
    terms: usize,
    terms_ok: usize,
    blockers: BTreeMap<String, usize>,
    envs: usize,
    /// The context's attribute layout per environment, from the schema.
    contexts: BTreeMap<(String, String, String), Vec<(String, Kind)>>,
}

fn compile(policies: &PolicySet, schema: &Schema) -> Compiled {
    let mut c = Compiled { groups: vec![], layouts: Layouts::new(), terms: 0, terms_ok: 0, blockers: BTreeMap::new(), envs: 0, contexts: BTreeMap::new() };
    for env in schema.request_envs() {
        c.envs += 1;
        let (mut permits, mut forbids, mut ok) = (vec![], vec![], true);
        let key = (env.principal().to_string(), AsRef::<str>::as_ref(env.action().id()).to_string(), env.resource().to_string());
        match SymEnv::new(schema, &env).map(|e| gen::kind_of(&e.request.context.type_of())) {
            Ok(Kind::Record(layout)) => {
                c.contexts.insert(key.clone(), layout);
            }
            _ => {
                *c.blockers.entry("a request context the schema does not type as a record".into()).or_default() += 1;
                ok = false;
            }
        }
        if env.action().type_name().to_string() != "Action" {
            *c.blockers.entry("an action in a namespace".into()).or_default() += 1;
            ok = false;
        }
        for p in policies.policies() {
            c.terms += 1;
            let term = match CompiledPolicy::compile(p, &env, schema) {
                Ok(cp) => never_matches_asserts(&cp).asserts().last().unwrap().clone(),
                Err(e) => {
                    *c.blockers.entry(format!("symbolic compiler: {e}")).or_default() += 1;
                    ok = false;
                    continue;
                }
            };
            // Translate each term alone first, so coverage is counted per term.
            let mut scratch = Layouts::new();
            match EnvGen::new(&mut scratch).finish(&[term.clone()], &[]) {
                Ok(_) => c.terms_ok += 1,
                Err(why) => {
                    *c.blockers.entry(why).or_default() += 1;
                    ok = false;
                }
            }
            match p.effect() {
                Effect::Permit => permits.push(term),
                Effect::Forbid => forbids.push(term),
            }
        }
        if !ok {
            continue;
        }
        let (body, needs) = EnvGen::new(&mut c.layouts).finish(&permits, &forbids).expect("terms translated alone");
        match c.groups.iter_mut().find(|g| g.body == body) {
            Some(g) => g.envs.push(key),
            None => c.groups.push(Group { body, needs, envs: vec![key] }),
        }
    }
    c
}

fn supported(c: &Compiled) -> bool {
    c.blockers.is_empty() && !c.groups.is_empty()
}

fn arr(b: &[u8]) -> String {
    format!("[{}]", b.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", "))
}

fn rows(v: &[[u8; 32]]) -> String {
    format!("[{}]", v.iter().map(|x| arr(x)).collect::<Vec<_>>().join(", "))
}

fn emit(c: &Compiled, policy_hash: &[u8; 32], schema_hash: &[u8; 32], set: &str) -> String {
    let ne = c.groups.iter().map(|g| g.needs.ents.len()).max().unwrap().max(1);
    let ns = c.groups.iter().map(|g| g.needs.sets.len()).max().unwrap().max(1);
    let nr = c.groups.iter().map(|g| g.needs.recs.len()).max().unwrap().max(1);
    let mut s = String::new();
    writeln!(s, "// Generated by cedar-to-noir from corpus set `{set}`. Do not edit.").unwrap();
    writeln!(s, "// Everything down to the line of dashes is the fixed library.\n").unwrap();
    s += PRELUDE;
    writeln!(s, "\n// ---------------------------------------------------------------- generated\n").unwrap();
    writeln!(s, "global POLICY_HASH: [u8; 32] = {};", arr(policy_hash)).unwrap();
    writeln!(s, "global SCHEMA_HASH: [u8; 32] = {};", arr(schema_hash)).unwrap();
    writeln!(s, "global NE: u32 = {ne}; // opened entities\nglobal NS: u32 = {ns}; // opened set attributes\nglobal NR: u32 = {nr}; // opened record attributes\n").unwrap();
    let params = "sel: bool, p_uid: [u8; 32], r_uid: [u8; 32], ents: [Entity; NE], ent_ok: [bool; NE], sets: [[[u8; 32]; MAX_SET]; NS], set_h: [[u8; 32]; NS], recs: [Rec; NR], rec_h: [[u8; 32]; NR], ctx: Rec";
    for (i, g) in c.groups.iter().enumerate() {
        for (p, a, r) in &g.envs {
            writeln!(s, "// {p} does {a} on {r}").unwrap();
        }
        writeln!(s, "fn env_{i}({params}) -> bool {{\n{}\n}}\n", g.body).unwrap();
    }
    s += "fn main(\n    request_hash: pub [u8; 32],\n    policy_hash: pub [u8; 32],\n    schema_hash: pub [u8; 32],\n    entities_root: pub [u8; 32],\n    nonce: pub BoundedVec<u8, MAX_NONCE>,\n    decision: pub bool,\n    context_hash: pub [u8; 32],\n    ctx: Rec,\n    subject_type: BoundedVec<u8, MAX_TYPE>,\n    subject_id: BoundedVec<u8, MAX_ID>,\n    action: BoundedVec<u8, MAX_ACTION>,\n    resource_type: BoundedVec<u8, MAX_TYPE>,\n    resource_id: BoundedVec<u8, MAX_ID>,\n    ents: [Entity; NE],\n    sets: [[[u8; 32]; MAX_SET]; NS],\n    recs: [Rec; NR],\n) {\n";
    s += "    assert(policy_hash == POLICY_HASH);\n    assert(schema_hash == SCHEMA_HASH);\n";
    for f in ["subject_type", "subject_id", "action", "resource_type", "resource_id", "nonce"] {
        writeln!(s, "    assert_plain({f});").unwrap();
    }
    s += "    assert(request_digest(subject_type, subject_id, action, resource_type, resource_id, nonce) == request_hash);\n";
    s += "    assert(rec_digest(ctx.present, ctx.slots) == context_hash);\n";
    s += "    let p_uid = uid_hash(subject_type, subject_id);\n    let r_uid = uid_hash(resource_type, resource_id);\n";
    s += "    let mut ent_ok = [false; NE];\n    for k in 0..NE {\n        ent_ok[k] = opens(ents[k], entities_root);\n    }\n";
    s += "    let mut set_h = [ZERO; NS];\n    for j in 0..NS {\n        set_h[j] = set_digest(sets[j]);\n    }\n";
    s += "    let mut rec_h = [ZERO; NR];\n    for j in 0..NR {\n        rec_h[j] = rec_digest(recs[j].present, recs[j].slots);\n    }\n";
    for (i, g) in c.groups.iter().enumerate() {
        let sel: Vec<String> = g
            .envs
            .iter()
            .map(|(p, a, r)| format!("(eq_str(subject_type, \"{p}\") & eq_str(action, \"{a}\") & eq_str(resource_type, \"{r}\"))"))
            .collect();
        writeln!(s, "    let sel_{i} = {};", sel.join("\n        | ")).unwrap();
        writeln!(s, "    let d_{i} = env_{i}(sel_{i}, p_uid, r_uid, ents, ent_ok, sets, set_h, recs, rec_h, ctx);").unwrap();
    }
    let n = c.groups.len();
    writeln!(s, "    // The request fits the schema.\n    assert({});", (0..n).map(|i| format!("sel_{i}")).collect::<Vec<_>>().join(" | ")).unwrap();
    writeln!(s, "    assert(decision == ({}));\n}}", (0..n).map(|i| format!("(sel_{i} & d_{i})")).collect::<Vec<_>>().join(" | ")).unwrap();
    s
}

/// The context's attributes: everything but the verifier's nonce and epoch.
fn context_attrs(req: &Value) -> Value {
    let mut c = req["context"].as_object().cloned().unwrap_or_default();
    c.remove("nonce");
    c.remove("epoch");
    Value::Object(c)
}

/// The request whose canonical bytes are hashed: its context holds only the nonce.
fn reduced_request(req: &Value) -> Value {
    let mut r = req.clone();
    let nonce = req.pointer("/context/nonce").cloned();
    r["context"] = match nonce {
        Some(n) => json!({ "nonce": n }),
        None => json!({}),
    };
    r
}

/// The concrete value of a term that names an entity, a set or a record, as Cedar JSON. Null when absent.
fn path_eval(t: &Term, req: &Value, store: &RecordStore) -> Result<Value, String> {
    Ok(match t {
        Term::Var(v) if v.id == "principal" => json!({ "__entity": req["subject"] }),
        Term::Var(v) if v.id == "resource" => json!({ "__entity": req["resource"] }),
        Term::Var(v) if v.id == "context" => context_attrs(req),
        Term::Some(x) => path_eval(x, req, store)?,
        Term::App { op: Op::OptionGet, args, .. } => path_eval(&args[0], req, store)?,
        Term::App { op: Op::RecordGet(a), args, .. } => path_eval(&args[0], req, store)?.get(a.as_str()).cloned().unwrap_or(Value::Null),
        Term::App { op: Op::Uuf(f), args, .. } if f.id.starts_with("attrs[") => {
            let e = path_eval(&args[0], req, store)?;
            match uid_text(&e) {
                Some(uid) => store.json.get(&uid).cloned().unwrap_or(Value::Null),
                None => Value::Null,
            }
        }
        _ => return Err("an entity reached through a computed expression".into()),
    })
}

fn bounded(name: &str, s: &str, max: usize) -> Result<String, String> {
    if s.len() > max {
        return Err(format!("{name} is longer than {max} bytes"));
    }
    let mut b = s.as_bytes().to_vec();
    b.resize(max, 0);
    Ok(format!("[{name}]\nstorage = {}\nlen = {}\n\n", arr(&b), s.len()))
}

fn input(c: &Compiled, r: &Value, store: &RecordStore, policy_hash: &[u8; 32], schema_hash: &[u8; 32]) -> Result<String, String> {
    let req = &r["request"];
    let f = |p: &str| req.pointer(p).and_then(Value::as_str).unwrap_or("").to_owned();
    let key = (f("/subject/type"), f("/action/name"), f("/resource/type"));
    let g = c.groups.iter().find(|g| g.envs.contains(&key)).ok_or("the request fits no environment of the schema")?;
    let ne = c.groups.iter().map(|g| g.needs.ents.len()).max().unwrap().max(1);
    let ns = c.groups.iter().map(|g| g.needs.sets.len()).max().unwrap().max(1);
    let nr = c.groups.iter().map(|g| g.needs.recs.len()).max().unwrap().max(1);

    let mut t = String::new();
    let layout = c.contexts.get(&key).ok_or("no context layout for this environment")?;
    let attrs = context_attrs(req);
    let (ctx_present, ctx_slots) = record_block(attrs.as_object().unwrap(), layout)?;
    writeln!(t, "request_hash = {}", arr(&sha256(&canonical_request(&reduced_request(req))))).unwrap();
    writeln!(t, "context_hash = {}", arr(&sha256(&block_bytes(ctx_present, &ctx_slots)))).unwrap();
    writeln!(t, "policy_hash = {}", arr(policy_hash)).unwrap();
    writeln!(t, "schema_hash = {}", arr(schema_hash)).unwrap();
    writeln!(t, "entities_root = {}", arr(&store.root)).unwrap();
    writeln!(t, "decision = {}", r["oracle"]["decision"]).unwrap();
    let mut sets = vec![[[0u8; 32]; MAX_SET]; ns];
    for (j, (term, kind)) in g.needs.sets.iter().enumerate() {
        let v = path_eval(term, req, store)?;
        if !v.is_null() {
            sets[j] = set_block(&v, kind)?;
        }
    }
    writeln!(t, "sets = [{}]\n", sets.iter().map(|s| rows(s)).collect::<Vec<_>>().join(", ")).unwrap();
    writeln!(t, "[ctx]\npresent = {ctx_present}\nslots = {}\n", rows(&ctx_slots)).unwrap();
    t += &bounded("nonce", &f("/context/nonce"), 32)?;
    t += &bounded("subject_type", &key.0, 24)?;
    t += &bounded("subject_id", &f("/subject/id"), 48)?;
    t += &bounded("action", &key.1, 32)?;
    t += &bounded("resource_type", &key.2, 24)?;
    t += &bounded("resource_id", &f("/resource/id"), 48)?;
    for k in 0..ne {
        let opened = match g.needs.ents.get(k) {
            Some(term) => {
                let e = path_eval(term, req, store)?;
                match uid_text(&e) {
                    Some(uid) => Some(store.open(&uid).ok_or(format!("{uid} is not in the entity store"))?),
                    None => None,
                }
            }
            None => None,
        };
        let mut sib = vec![[0u8; 32]; MAX_DEPTH];
        let mut left = vec![false; MAX_DEPTH];
        let (uid_h, present, attrs, ancs, len) = match &opened {
            Some((rec, path)) => {
                if path.len() > MAX_DEPTH {
                    return Err("the entity store is deeper than the circuit allows".into());
                }
                for (i, s) in path.iter().enumerate() {
                    sib[i] = s.sibling;
                    left[i] = s.sibling_is_left;
                }
                (rec.uid_h, rec.present, rec.attrs, rec.ancestors, path.len())
            }
            None => ([0u8; 32], 0, [[0u8; 32]; MAX_ATTRS], [[0u8; 32]; MAX_ANC], 0),
        };
        writeln!(t, "[[ents]]\nuid_h = {}\npresent = {present}\nattrs = {}\nancestors = {}\npath = {}", arr(&uid_h), rows(&attrs), rows(&ancs), rows(&sib)).unwrap();
        writeln!(t, "sibling_is_left = [{}]\npath_len = {len}\n", left.iter().map(|b| b.to_string()).collect::<Vec<_>>().join(", ")).unwrap();
    }
    for j in 0..nr {
        let (present, slots) = match g.needs.recs.get(j) {
            Some((term, layout)) => match path_eval(term, req, store)? {
                Value::Object(o) => record_block(&o, layout)?,
                _ => (0, [[0u8; 32]; MAX_ATTRS]),
            },
            None => (0, [[0u8; 32]; MAX_ATTRS]),
        };
        writeln!(t, "[[recs]]\npresent = {present}\nslots = {}\n", rows(&slots)).unwrap();
    }
    Ok(t)
}

struct Loaded {
    policies: PolicySet,
    schema: Schema,
    manifest: Value,
    dir: std::path::PathBuf,
}

fn load(repo: &Path, set: &str) -> Loaded {
    let dir = repo.join("corpus/sets").join(set);
    let manifest: Value = serde_json::from_slice(&fs::read(repo.join("corpus/MANIFEST.json")).unwrap()).unwrap();
    Loaded {
        policies: PolicySet::from_str(&fs::read_to_string(dir.join("policies.cedar")).unwrap()).unwrap(),
        schema: Schema::from_cedarschema_str(&fs::read_to_string(dir.join("schema.cedarschema")).unwrap()).unwrap().0,
        manifest: manifest["sets"][set].clone(),
        dir,
    }
}

fn main() {
    let a: Vec<String> = std::env::args().collect();
    let repo = Path::new(&a[2]);
    match a[1].as_str() {
        "coverage" => {
            let mut names: Vec<String> = fs::read_dir(repo.join("corpus/sets")).unwrap().map(|e| e.unwrap().file_name().to_string_lossy().into_owned()).collect();
            names.sort();
            for set in names {
                let l = load(repo, &set);
                let c = compile(&l.policies, &l.schema);
                println!(
                    "{}",
                    json!({
                        "set": set, "policy_hash": l.manifest["policy_hash"], "policies": l.manifest["policies"],
                        "environments": c.envs, "terms": c.terms, "terms_translated": c.terms_ok,
                        "compiles": supported(&c), "blockers": c.blockers, "functions": c.groups.len(),
                        "opened_entities": c.groups.iter().map(|g| g.needs.ents.len()).max(),
                        "opened_sets": c.groups.iter().map(|g| g.needs.sets.len()).max(),
                        "opened_records": c.groups.iter().map(|g| g.needs.recs.len()).max(),
                    })
                );
            }
        }
        "compile" => {
            let (set, out) = (&a[3], Path::new(&a[4]));
            let l = load(repo, set);
            let c = compile(&l.policies, &l.schema);
            if !supported(&c) {
                eprintln!("`{set}` does not compile: {:?}", c.blockers);
                std::process::exit(2);
            }
            let policy_hash = parse_hex_hash(l.manifest["policy_hash"].as_str().unwrap()).unwrap();
            let schema_hash = parse_hex_hash(l.manifest["schema_hash"].as_str().unwrap()).unwrap();
            fs::create_dir_all(out.join("src")).unwrap();
            fs::create_dir_all(out.join("inputs")).unwrap();
            fs::write(out.join("Nargo.toml"), "[package]\nname = \"policy\"\ntype = \"bin\"\nauthors = [\"\"]\n\n[dependencies]\nsha256 = { tag = \"v0.3.0\", git = \"https://github.com/noir-lang/sha256\" }\n").unwrap();
            fs::write(out.join("src/main.nr"), emit(&c, &policy_hash, &schema_hash, set)).unwrap();

            let entities: Value = serde_json::from_slice(&fs::read(l.dir.join("entities.json")).unwrap()).unwrap();
            let store = match RecordStore::new(&entities, &c.layouts) {
                Ok(s) => s,
                Err(e) => {
                    eprintln!("`{set}` compiles, but its entity store cannot be committed: {e}");
                    std::process::exit(3);
                }
            };
            let mut index = Vec::new();
            for (n, line) in fs::read_to_string(l.dir.join("requests.jsonl")).unwrap().lines().enumerate() {
                let r: Value = serde_json::from_str(line).unwrap();
                match input(&c, &r, &store, &policy_hash, &schema_hash) {
                    Ok(t) => {
                        fs::write(out.join(format!("inputs/{n}.toml")), t).unwrap();
                        index.push(json!({ "n": n, "name": r["name"], "decision": r["oracle"]["decision"], "request_hash": hex_hash(&sha256(&canonical_request(&reduced_request(&r["request"])))) }));
                    }
                    Err(e) => index.push(json!({ "n": n, "name": r["name"], "skipped": e, "request_hash": r["request_hash"] })),
                }
            }
            let idx = json!({
                "set": set, "policy_hash": l.manifest["policy_hash"], "schema_hash": l.manifest["schema_hash"],
                "entities": { "type": "merkle-sha256-record-v0", "root": hex_hash(&store.root) },
                "functions": c.groups.len(), "requests": index,
            });
            fs::write(out.join("inputs/index.json"), serde_json::to_string_pretty(&idx).unwrap() + "\n").unwrap();
            println!("{set}: {} functions for {} environments, {} inputs", c.groups.len(), c.envs, idx["requests"].as_array().unwrap().iter().filter(|r| r.get("skipped").is_none()).count());
        }
        other => panic!("unknown command {other}"),
    }
}
