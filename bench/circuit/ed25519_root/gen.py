#!/usr/bin/env python3
"""Constants and test inputs for the Ed25519 check over a signed root.

  gen.py consts            write ../ed25519/src/consts.nr (SHA-512 and curve constants, computed here, not typed)
  gen.py inputs <out dir>  sign test roots with a fresh key and write honest and tampered inputs

The signed message is b"zk-pdp-root-v0" || root (32 bytes) || epoch (8 bytes, big-endian), 54 bytes,
the same message the P-256 signed mode signs, but signed directly, as Ed25519 hashes internally.
"""
import hashlib, json, os, sys
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization

P = 2**255 - 19
L = 2**252 + 27742317777372353535851937790883648493
D = (-121665 * pow(121666, P - 2, P)) % P
SQRT_M1 = pow(2, (P - 1) // 4, P)
TAG = b"zk-pdp-root-v0"

def iroot(n, k):
    x = 1 << ((n.bit_length() + k - 1) // k)
    while True:
        y = ((k - 1) * x + n // x ** (k - 1)) // k
        if y >= x:
            return x
        x = y

def primes(n):
    ps, c = [], 2
    while len(ps) < n:
        if all(c % p for p in ps):
            ps.append(c)
        c += 1
    return ps

def limbs(v):
    return [(v >> (120 * i)) & ((1 << 120) - 1) for i in range(3)]

def recover_x(y, sign):
    x2 = (y * y - 1) * pow(D * y * y + 1, P - 2, P) % P
    x = pow(x2, (P + 3) // 8, P)
    if (x * x - x2) % P:
        x = x * SQRT_M1 % P
    assert (x * x - x2) % P == 0
    if x & 1 != sign:
        x = P - x
    return x

def decode(b):
    y = int.from_bytes(b, "little") & ((1 << 255) - 1)
    # Decoded mod p on purpose, so a non-canonical y still gets the x a cheating prover would supply.
    return recover_x(y % P, b[31] >> 7), y

def consts():
    K = [iroot(p << 192, 3) & (2**64 - 1) for p in primes(80)]
    H0 = [iroot(p << 128, 2) & (2**64 - 1) for p in primes(8)]
    assert H0[0] == 0x6A09E667F3BCC908 and K[0] == 0x428A2F98D728AE22 and K[79] == 0x6C44198C4A475817
    by = 4 * pow(5, P - 2, P) % P
    bx = recover_x(by, 0)
    f = lambda xs: ", ".join(hex(x) for x in xs)
    out = "// Generated by gen.py consts. Do not edit.\n"
    out += f"pub global SHA512_K: [u64; 80] = [{f(K)}];\n"
    out += f"pub global SHA512_H0: [u64; 8] = [{f(H0)}];\n"
    out += f"pub global ED_D: [u128; 3] = [{f(limbs(D))}];\n"
    out += f"pub global ED_BX: [u128; 3] = [{f(limbs(bx))}];\n"
    out += f"pub global ED_BY: [u128; 3] = [{f(limbs(by))}];\n"
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ed25519", "src", "consts.nr"), "w").write(out)

def toml(pk, root, epoch, sig, note):
    try:
        ax, _ = decode(pk)
    except AssertionError:
        ax = 0
    try:
        rx, _ = decode(sig[:32])
    except AssertionError:
        rx = 0
    q = lambda xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"
    return (f"# {note}\npk = {q(list(pk))}\nroot = {q(list(root))}\nepoch = \"{epoch}\"\n"
            f"sig = {q(list(sig))}\npk_x = {q(limbs(ax))}\nr_x = {q(limbs(rx))}\n")

def inputs(out):
    os.makedirs(out, exist_ok=True)
    key = Ed25519PrivateKey.generate()
    pk = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    cases = []
    for n in range(3):
        root = hashlib.sha256(b"root %d" % n).digest()
        epoch = 1000 + n
        msg = TAG + root + epoch.to_bytes(8, "big")
        sig = key.sign(msg)
        key.public_key().verify(sig, msg)
        cases.append((f"honest-{n}", pk, root, epoch, sig, True))
    pk0, root0, ep0, sig0 = cases[0][1:5]
    flip = lambda b, i: b[:i] + bytes([b[i] ^ 1]) + b[i + 1:]
    s = int.from_bytes(sig0[32:], "little")
    cases += [
        ("wrong-root", pk0, flip(root0, 5), ep0, sig0, False),
        ("wrong-epoch", pk0, root0, ep0 + 1, sig0, False),
        ("wrong-key", Ed25519PrivateKey.generate().public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw), root0, ep0, sig0, False),
        ("s-flipped", pk0, root0, ep0, sig0[:32] + flip(sig0[32:], 0), False),
        ("s-plus-L", pk0, root0, ep0, sig0[:32] + (s + L).to_bytes(32, "little"), False),
        ("r-from-other-sig", pk0, root0, ep0, cases[1][4][:32] + sig0[32:], False),
    ]
    # Encodings RFC 8032 refuses. y = p decodes to a real point of order 4 if accepted.
    enc = lambda y, sign=0: (y | (sign << 255)).to_bytes(32, "little")
    cases += [
        ("pk-y-equals-p", enc(P), root0, ep0, sig0, False),
        ("pk-identity", enc(1), root0, ep0, sig0, False),
        ("pk-order-2", enc(P - 1), root0, ep0, sig0, False),
        ("s-equals-L", pk0, root0, ep0, sig0[:32] + L.to_bytes(32, "little"), False),
    ]
    idx = []
    for name, pk_, root, epoch, sig, ok in cases:
        open(os.path.join(out, name + ".toml"), "w").write(toml(pk_, root, epoch, sig, name))
        idx.append({"name": name, "expect_valid": ok})
    json.dump(idx, open(os.path.join(out, "index.json"), "w"), indent=1)
    print("wrote", len(idx), "cases to", out)

if __name__ == "__main__":
    {"consts": lambda: consts(), "inputs": lambda: inputs(sys.argv[2])}[sys.argv[1]]()
