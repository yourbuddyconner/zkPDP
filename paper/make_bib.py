"""Write paper/references.bib: the entries main.tex cites, from the literature
bibliography, without the project's internal fields.

The literature file keeps reading notes in `note`, `keywords`, `readstatus`
and `readdetail`. Those are for us, not for readers, and their underscores
break BibTeX. Run from any directory: python3 paper/make_bib.py
"""

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE.parent / "docs" / "literature" / "references.bib"
TEX = HERE / "main.tex"
OUT = HERE / "references.bib"
DROP = {"note", "keywords", "readstatus", "readdetail", "abstract"}


def entries(text):
    """Yield (key, entry text) for each @type{key, ...} at brace depth 0."""
    i = 0
    while True:
        start = text.find("@", i)
        if start < 0:
            return
        open_brace = text.find("{", start)
        depth = 0
        for j in range(open_brace, len(text)):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    break
        body = text[start : j + 1]
        key = body[open_brace - start + 1 : body.index(",")].strip()
        yield key, body
        i = j + 1


def fields(body):
    """Split an entry body into its header and (name, value) fields."""
    header, rest = body.split(",", 1)
    rest = rest.rstrip()[:-1]  # the entry's closing brace
    out, i = [], 0
    while True:
        m = re.compile(r"\s*,?\s*([A-Za-z]+)\s*=\s*").match(rest, i)
        if not m or m.end() >= len(rest):
            break
        name, j = m.group(1).lower(), m.end()
        if rest[j] == "{":
            depth = 0
            for k in range(j, len(rest)):
                depth += {"{": 1, "}": -1}.get(rest[k], 0)
                if depth == 0:
                    break
            value, i = rest[j : k + 1], k + 1
        else:
            k = j
            while k < len(rest) and rest[k] not in ",\n":
                k += 1
            value, i = rest[j:k].strip(), k
        out.append((name, value))
    return header, out


def main():
    cited = set()
    for group in re.findall(r"\\cite[pt]?\*?\{([^}]*)\}", TEX.read_text()):
        cited.update(k.strip() for k in group.split(","))
    found = {}
    for key, body in entries(SOURCE.read_text()):
        if key in cited and key not in found:
            header, fs = fields(body)
            # Double braces keep a title's capitals (SoK, Cedar, SMT) as written.
            fs = [(n, "{" + v + "}" if n == "title" and v.startswith("{") and not v.startswith("{{") else v)
                  for n, v in fs]
            kept = [f"  {n} = {v}" for n, v in fs if n not in DROP]
            found[key] = header + ",\n" + ",\n".join(kept) + "\n}\n"
    missing = sorted(cited - found.keys())
    if missing:
        sys.exit(f"not in {SOURCE.name}: {', '.join(missing)}")
    OUT.write_text("% Generated by make_bib.py from docs/literature/references.bib. Do not edit.\n\n"
                   + "\n".join(found[k] for k in sorted(found)))
    print(f"{len(found)} entries written to {OUT.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
